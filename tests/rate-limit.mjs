import test from 'node:test'
import assert from 'node:assert/strict'
import { readFileSync } from 'node:fs'
import { PGlite } from '@electric-sql/pglite'
import { failClosed } from '../src/lib/rate-limit.ts'

const db = new PGlite()
await db.exec(`CREATE ROLE anon; CREATE ROLE authenticated; CREATE TABLE rate_limit (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  key text NOT NULL, identifier text NOT NULL, ip text, created_at timestamptz NOT NULL DEFAULT now());`)
await db.exec(readFileSync('supabase/migrations/015_rate_limit_atomico.sql', 'utf8'))
const reservar = async (identifier = 'u1', max = 3) => (await db.query(
  'SELECT * FROM public.reservar_rate_limit($1,$2,$3,$4,$5)', ['op', identifier, null, max, 3600]
)).rows[0]

test('la reserva cuenta e inserta en una sola operación y bloquea el exceso', async () => {
  for (let i = 0; i < 3; i++) {
    const fila = await reservar()
    assert.equal(fila.permitido, true)
    assert.equal(Number(fila.usados), i + 1)
  }
  const bloqueada = await reservar()
  assert.equal(bloqueada.permitido, false)
  assert.equal(Number(bloqueada.restantes), 0)
})

test('cada identificador tiene su propio presupuesto', async () => {
  assert.equal((await reservar('otro')).permitido, true)
})

test('las operaciones costosas fallan cerrado y la analítica no', () => {
  for (const key of ['auth:login', 'pagos:crear', 'r2-upload', 'ai-descripcion', 'producto:create']) {
    assert.equal(failClosed(key), true, key)
  }
  for (const key of ['track:evento', 'inmueble:visita', 'favorito:toggle']) {
    assert.equal(failClosed(key), false, key)
  }
})

test('la función no es ejecutable por anon ni authenticated', () => {
  const sql = readFileSync('supabase/migrations/015_rate_limit_atomico.sql', 'utf8')
  assert.match(sql, /REVOKE ALL ON FUNCTION public\.reservar_rate_limit\(text, text, text, integer, integer\) FROM PUBLIC, anon, authenticated/)
  assert.match(sql, /pg_advisory_xact_lock/)
})

test('el cron limpia registros antiguos de rate_limit y solo acepta secreto en cabecera', () => {
  const cron = readFileSync('src/app/api/cron/notificaciones-email/route.ts', 'utf8')
  assert.match(cron, /cleanOldRateLimits/)
  assert.match(cron, /timingSafeEqual/)
  assert.doesNotMatch(cron, /searchParams\.get\(['"]secret['"]\)/)
})

test.after(() => db.close())
