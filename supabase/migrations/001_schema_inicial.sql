CREATE TABLE IF NOT EXISTS public.conversaciones (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  user1_id uuid NOT NULL REFERENCES public.perfiles(id) ON DELETE CASCADE,
  user2_id uuid NOT NULL REFERENCES public.perfiles(id) ON DELETE CASCADE,
  producto_id uuid REFERENCES public.inmuebles(id) ON DELETE SET NULL,
  ultimo_mensaje text,
  ultimo_mensaje_contenido text,
  ultimo_mensaje_en timestamptz,
  creado_en timestamptz NOT NULL DEFAULT now(),
  actualizado_en timestamptz NOT NULL DEFAULT now(),
  CHECK (user1_id <> user2_id),
  CHECK (user1_id < user2_id),
  UNIQUE (user1_id, user2_id, producto_id)
);

CREATE TABLE IF NOT EXISTS public.mensajes (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  conversacion_id uuid NOT NULL REFERENCES public.conversaciones(id) ON DELETE CASCADE,
  remitente_id uuid NOT NULL REFERENCES public.perfiles(id) ON DELETE CASCADE,
  destinatario_id uuid NOT NULL REFERENCES public.perfiles(id) ON DELETE CASCADE,
  producto_id uuid REFERENCES public.inmuebles(id) ON DELETE SET NULL,
  contenido text NOT NULL CHECK (length(btrim(contenido)) BETWEEN 1 AND 5000),
  leido boolean NOT NULL DEFAULT false,
  creado_en timestamptz NOT NULL DEFAULT now(),
  CHECK (remitente_id <> destinatario_id)
);

CREATE OR REPLACE FUNCTION public.actualizar_conversacion_desde_mensaje()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, public
AS $$
BEGIN
  UPDATE public.conversaciones
     SET ultimo_mensaje = NEW.contenido,
         ultimo_mensaje_contenido = NEW.contenido,
         ultimo_mensaje_en = NEW.creado_en,
         actualizado_en = now()
   WHERE id = NEW.conversacion_id;
  RETURN NEW;
END;
$$;

REVOKE ALL ON FUNCTION public.actualizar_conversacion_desde_mensaje() FROM PUBLIC;
DROP TRIGGER IF EXISTS mensajes_actualizar_conversacion ON public.mensajes;
CREATE TRIGGER mensajes_actualizar_conversacion
  AFTER INSERT ON public.mensajes
  FOR EACH ROW EXECUTE FUNCTION public.actualizar_conversacion_desde_mensaje();

