CREATE OR REPLACE FUNCTION public.resenas_guardar_titulo_inmueble()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, public
AS $$
BEGIN
  IF NEW.producto_titulo IS NULL THEN
    SELECT titulo INTO NEW.producto_titulo FROM public.inmuebles WHERE id = NEW.producto_id;
  END IF;
  RETURN NEW;
END;
$$;

REVOKE ALL ON FUNCTION public.resenas_guardar_titulo_inmueble() FROM PUBLIC;
DROP TRIGGER IF EXISTS resenas_titulo_inmueble ON public.resenas;
CREATE TRIGGER resenas_titulo_inmueble
  BEFORE INSERT ON public.resenas
  FOR EACH ROW EXECUTE FUNCTION public.resenas_guardar_titulo_inmueble();

