CREATE OR REPLACE FUNCTION public.aprobar_transaccion(
  p_transaccion_id uuid,
  p_admin_id uuid DEFAULT NULL
)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, public, auth
AS $$
DECLARE
  v_tx public.transacciones_creditos%ROWTYPE;
BEGIN
  IF coalesce(auth.role(), '') <> 'service_role' THEN
    IF auth.uid() IS DISTINCT FROM p_admin_id OR NOT public.is_admin() THEN
      RAISE EXCEPTION 'No autorizado' USING ERRCODE = '42501';
    END IF;
  END IF;

  SELECT * INTO v_tx
    FROM public.transacciones_creditos
   WHERE id = p_transaccion_id
   FOR UPDATE;

  IF NOT FOUND THEN
    RAISE EXCEPTION 'Transacción no encontrada' USING ERRCODE = 'P0002';
  END IF;
  IF v_tx.estado <> 'pendiente' THEN
    RAISE EXCEPTION 'La transacción ya fue procesada' USING ERRCODE = '22023';
  END IF;

  UPDATE public.perfiles
     SET credito_balance = credito_balance + v_tx.monto
   WHERE id = v_tx.user_id;

  UPDATE public.transacciones_creditos
     SET estado = 'aprobado', aprobado_en = now(), aprobado_por = p_admin_id,
         actualizado_en = now()
   WHERE id = p_transaccion_id;
END;
$$;

CREATE OR REPLACE FUNCTION public.usar_boost(
  p_producto_id uuid,
  p_user_id uuid
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, public, auth
AS $$
DECLARE
  v_owner uuid;
  v_balance numeric(12,2);
BEGIN
  IF auth.uid() IS DISTINCT FROM p_user_id AND NOT public.is_admin() THEN
    RETURN jsonb_build_object('ok', false, 'error', 'No autorizado');
  END IF;

  SELECT usuario_id INTO v_owner
    FROM public.inmuebles
   WHERE id = p_producto_id
   FOR UPDATE;
  IF NOT FOUND OR v_owner <> p_user_id THEN
    RETURN jsonb_build_object('ok', false, 'error', 'Publicación no encontrada');
  END IF;

  UPDATE public.perfiles
     SET credito_balance = credito_balance - 1
   WHERE id = p_user_id AND credito_balance >= 1
   RETURNING credito_balance INTO v_balance;
  IF NOT FOUND THEN
    RETURN jsonb_build_object('ok', false, 'error', 'No tienes créditos suficientes');
  END IF;

  UPDATE public.inmuebles
     SET boosteado_en = now(), actualizado_en = now()
   WHERE id = p_producto_id;

  RETURN jsonb_build_object('ok', true, 'balance', v_balance);
END;
$$;

CREATE OR REPLACE FUNCTION public.usar_destacado(
  p_producto_id uuid,
  p_user_id uuid,
  p_horas integer
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, public, auth
AS $$
DECLARE
  v_owner uuid;
  v_balance numeric(12,2);
  v_creditos integer;
BEGIN
  IF auth.uid() IS DISTINCT FROM p_user_id AND NOT public.is_admin() THEN
    RETURN jsonb_build_object('ok', false, 'error', 'No autorizado');
  END IF;

  v_creditos := CASE p_horas WHEN 24 THEN 6 WHEN 48 THEN 10 ELSE 0 END;
  IF v_creditos = 0 THEN
    RETURN jsonb_build_object('ok', false, 'error', 'Duración de destacado no válida');
  END IF;

  SELECT usuario_id INTO v_owner
    FROM public.inmuebles
   WHERE id = p_producto_id AND activo = true
   FOR UPDATE;
  IF NOT FOUND OR v_owner <> p_user_id THEN
    RETURN jsonb_build_object('ok', false, 'error', 'Publicación no encontrada o inactiva');
  END IF;

  UPDATE public.perfiles
     SET credito_balance = credito_balance - v_creditos
   WHERE id = p_user_id AND credito_balance >= v_creditos
   RETURNING credito_balance INTO v_balance;
  IF NOT FOUND THEN
    RETURN jsonb_build_object('ok', false, 'error', 'No tienes créditos suficientes');
  END IF;

  UPDATE public.inmuebles
     SET destacado = true,
         destacado_hasta = now() + make_interval(hours => p_horas),
         actualizado_en = now()
   WHERE id = p_producto_id;

  INSERT INTO public.destacados (producto_id, user_id, inicio, fin, pagado, creditos_usados)
  VALUES (p_producto_id, p_user_id, now(), now() + make_interval(hours => p_horas), true, v_creditos);

  RETURN jsonb_build_object('ok', true, 'balance', v_balance);
END;
$$;

CREATE OR REPLACE FUNCTION public.limpiar_auditoria_antigua()
RETURNS integer
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, public, auth
AS $$
DECLARE
  v_eliminadas integer;
BEGIN
  IF NOT public.is_admin() THEN
    RAISE EXCEPTION 'No autorizado' USING ERRCODE = '42501';
  END IF;
  DELETE FROM public.auditoria WHERE fecha_registro < now() - interval '180 days';
  GET DIAGNOSTICS v_eliminadas = ROW_COUNT;
  RETURN v_eliminadas;
END;
$$;

