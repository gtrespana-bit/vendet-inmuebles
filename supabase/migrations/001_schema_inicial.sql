CREATE OR REPLACE FUNCTION public.handle_new_auth_user()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, public, auth
AS $$
BEGIN
  INSERT INTO public.perfiles (id, nombre, email)
  VALUES (
    NEW.id,
    coalesce(
      nullif(NEW.raw_user_meta_data ->> 'nombre_completo', ''),
      nullif(NEW.raw_user_meta_data ->> 'nombre', '')
    ),
    NEW.email
  )
  ON CONFLICT (id) DO UPDATE
    SET email = EXCLUDED.email,
        nombre = coalesce(nullif(public.perfiles.nombre, ''), EXCLUDED.nombre);
  RETURN NEW;
END;
$$;

REVOKE ALL ON FUNCTION public.handle_new_auth_user() FROM PUBLIC;
DROP TRIGGER IF EXISTS on_auth_user_created_vendet ON auth.users;
CREATE TRIGGER on_auth_user_created_vendet
  AFTER INSERT ON auth.users
  FOR EACH ROW EXECUTE FUNCTION public.handle_new_auth_user();

DROP TRIGGER IF EXISTS perfiles_set_updated_at ON public.perfiles;
CREATE TRIGGER perfiles_set_updated_at
  BEFORE UPDATE ON public.perfiles
  FOR EACH ROW EXECUTE FUNCTION public.set_updated_at_column();

