CREATE OR REPLACE FUNCTION public.set_inmueble_defaults()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = pg_catalog, public
AS $$
BEGIN
  IF NEW.slug IS NULL OR btrim(NEW.slug) = '' THEN
    NEW.slug := coalesce(nullif(public.slugify(NEW.titulo), ''), 'inmueble')
      || '-' || left(NEW.id::text, 8);
  ELSE
    NEW.slug := public.slugify(NEW.slug);
  END IF;
  IF NEW.publicado_en IS NULL AND NEW.activo THEN
    NEW.publicado_en := now();
  END IF;
  NEW.actualizado_en := now();
  RETURN NEW;
END;
$$;

REVOKE ALL ON FUNCTION public.set_inmueble_defaults() FROM PUBLIC;
DROP TRIGGER IF EXISTS inmuebles_set_defaults ON public.inmuebles;
CREATE TRIGGER inmuebles_set_defaults
  BEFORE INSERT OR UPDATE ON public.inmuebles
  FOR EACH ROW EXECUTE FUNCTION public.set_inmueble_defaults();

